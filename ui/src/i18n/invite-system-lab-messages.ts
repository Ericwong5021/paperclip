function locale(): LabLocale {
  try {
    if (window.localStorage.getItem("paperclip.locale") === "zh-CN") return "zh-CN";
  } catch {
  }
  return typeof navigator !== "undefined" && navigator.language.toLowerCase().startsWith("zh")
    ? "zh-CN"
    : "en";
}

